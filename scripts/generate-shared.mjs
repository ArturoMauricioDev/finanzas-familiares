import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const generatedHeader = "// Generated by scripts/generate-shared.mjs. Do not edit by hand.\n";
const generatedCssHeader = "/* Generated by scripts/generate-shared.mjs. Do not edit by hand. */\n";

function kebab(value) {
  return String(value)
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/[_\s]+/g, "-")
    .toLowerCase();
}

async function readJson(relativePath) {
  return JSON.parse(await readFile(path.join(root, relativePath), "utf8"));
}

async function readText(relativePath) {
  return readFile(path.join(root, relativePath), "utf8");
}

function json(value) {
  return JSON.stringify(value, null, 2);
}

function buildTokens(tokens) {
  const colorKeys = Object.keys(tokens.color.light);
  const typeKeys = Object.keys(tokens.typography);
  const shapeKeys = Object.keys(tokens.shape);
  const spacingKeys = Object.keys(tokens.spacing);
  const elevationKeys = Object.keys(tokens.elevation);

  const lines = [
    "export const brand = " + json(tokens.brand) + " as const;",
    "export const seed = " + JSON.stringify(tokens.seed) + ";",
    "export const lightColors = " + json(tokens.color.light) + " as const;",
    "export const darkColors = " + json(tokens.color.dark) + " as const;",
    "export type ThemeMode = \"light\" | \"dark\";",
    "export type ColorName = keyof typeof lightColors;",
    "export type ThemeColors = Record<ColorName, string>;",
    "export const colorsByMode: Record<ThemeMode, ThemeColors> = { light: lightColors, dark: darkColors };",
    "export const typography = " + json(tokens.typography) + " as const;",
    "export type TypographyName = keyof typeof typography;",
    "export const shape = " + json(tokens.shape) + " as const;",
    "export const spacing = " + json(tokens.spacing) + " as const;",
    "export const elevation = " + json(tokens.elevation) + " as const;",
    "export const motion = " + json(tokens.motion) + " as const;",
    "export const breakpoints = " + json(tokens.breakpoints) + " as const;",
    "export const iconSize = " + json(tokens.iconSize) + " as const;",
    "export const touchTarget = " + json(tokens.touchTarget) + " as const;",
    "export const typographyNames = " + json(typeKeys) + " as const;",
    "export const colorNames = " + json(colorKeys) + " as const;",
    "export const shapeNames = " + json(shapeKeys) + " as const;",
    "export const spacingNames = " + json(spacingKeys) + " as const;",
    "export const elevationNames = " + json(elevationKeys) + " as const;",
    "",
  ];

  return generatedHeader + lines.join("\n");
}

function buildTokenCss(tokens) {
  const colorBlock = (mode) => {
    const entries = Object.entries(tokens.color[mode]).map(
      ([key, value]) => `  --md-sys-color-${kebab(key)}: ${value};`,
    );
    return entries.join("\n");
  };

  const typographyBlock = Object.entries(tokens.typography)
    .flatMap(([key, value]) => [
      `  --md-sys-typescale-${kebab(key)}-size: ${value.fontSize}px;`,
      `  --md-sys-typescale-${kebab(key)}-line-height: ${value.lineHeight}px;`,
      `  --md-sys-typescale-${kebab(key)}-weight: ${value.fontWeight};`,
      `  --md-sys-typescale-${kebab(key)}-tracking: ${value.letterSpacing}px;`,
    ])
    .join("\n");

  const shapeBlock = Object.entries(tokens.shape)
    .map(([key, value]) => `  --md-sys-shape-${kebab(key)}: ${value}px;`)
    .join("\n");

  const spacingBlock = Object.entries(tokens.spacing)
    .map(([key, value]) => `  --md-sys-spacing-${kebab(key)}: ${value}px;`)
    .join("\n");

  const elevationBlock = Object.entries(tokens.elevation)
    .map(([key, value]) => `  --md-sys-elevation-${kebab(key)}: ${value.web};`)
    .join("\n");

  const motionBlock = [
    `  --md-sys-motion-duration-short: ${tokens.motion.durationShort}ms;`,
    `  --md-sys-motion-duration-medium: ${tokens.motion.durationMedium}ms;`,
    `  --md-sys-motion-duration-long: ${tokens.motion.durationLong}ms;`,
    `  --md-sys-motion-duration-extra-long: ${tokens.motion.durationExtraLong}ms;`,
    `  --md-sys-motion-easing-standard: ${tokens.motion.easingStandard};`,
    `  --md-sys-motion-easing-emphasized: ${tokens.motion.easingEmphasized};`,
  ].join("\n");

  const breakpointBlock = Object.entries(tokens.breakpoints)
    .filter(([key]) => key !== "compact")
    .map(([key, value]) => `  --md-sys-breakpoint-${kebab(key)}: ${value}px;`)
    .join("\n");

  const themeColors = Object.keys(tokens.color.light)
    .map((key) => `  --color-${kebab(key)}: var(--md-sys-color-${kebab(key)});`)
    .join("\n");

  const themeShapes = Object.entries(tokens.shape)
    .map(([key]) => `  --radius-${kebab(key)}: var(--md-sys-shape-${kebab(key)});`)
    .join("\n");

  const themeTypography = Object.entries(tokens.typography)
    .map(
      ([key]) =>
        `  --text-${kebab(key)}: var(--md-sys-typescale-${kebab(key)}-size);\n  --text-${kebab(key)}--line-height: var(--md-sys-typescale-${kebab(key)}-line-height);`,
    )
    .join("\n");

  return [
    generatedCssHeader,
    ":root {",
    "  color-scheme: light;",
    colorBlock("light"),
    typographyBlock,
    shapeBlock,
    spacingBlock,
    elevationBlock,
    motionBlock,
    breakpointBlock,
    `  --md-sys-color-seed: ${tokens.seed};`,
    `  --md-sys-touch-target-min: ${tokens.touchTarget.min}px;`,
    "}",
    "",
    "[data-theme=\"dark\"] {",
    "  color-scheme: dark;",
    colorBlock("dark"),
    "}",
    "",
    "@theme inline {",
    "  --font-sans: var(--font-inter), Inter, system-ui, sans-serif;",
    themeColors,
    themeShapes,
    themeTypography,
    "}",
    "",
  ].join("\n");
}

function buildErrorKeys(errorKeys) {
  return [
    generatedHeader,
    "export const errorDetailKeys = " + json(errorKeys.details) + " as const;",
    "export const errorStatusKeys = " + json(errorKeys.statuses) + " as const;",
    "",
  ].join("\n");
}

function buildAvatarOptions(avatarOptions) {
  return [
    generatedHeader,
    "export const avatarOptions = " + json(avatarOptions) + " as const;",
    "export default avatarOptions;",
    "",
  ].join("\n");
}

function buildAvatarEngine(source) {
  return source.replace(
    'import options from "./avatar-options.json";',
    'import options from "./avatar-options.generated";',
  );
}

function buildMessages(es, en) {
  return [
    generatedHeader,
    "export const messages = {",
    "  es: " + json(es) + ",",
    "  en: " + json(en) + ",",
    "} as const;",
    "export const supportedLocales = [\"es\", \"en\"] as const;",
    "export type Locale = (typeof supportedLocales)[number];",
    "export const defaultLocale: Locale = \"es\";",
    "",
  ].join("\n");
}

function buildCurrencies(currencies) {
  return [
    generatedHeader,
    "export const currencyRegions = " + json(currencies.regions) + " as const;",
    "export type CurrencyRegion = keyof typeof currencyRegions | \"other\";",
    "export const countryCurrency = " + json(currencies.countryCurrency) + " as const;",
    "export type CountryCode = keyof typeof countryCurrency;",
    "",
  ].join("\n");
}

export async function buildFiles() {
  const [tokens, avatarOptions, errorKeys, engine, es, en, currencies] = await Promise.all([
    readJson("design-tokens/tokens.json"),
    readJson("shared/avatar/avatar-options.json"),
    readJson("shared/errors/error-keys.json"),
    readText("shared/avatar/avatar-engine.ts"),
    readJson("shared/i18n/es.json"),
    readJson("shared/i18n/en.json"),
    readJson("shared/currencies/regions.json"),
  ]);

  const files = new Map();
  const tokensTs = buildTokens(tokens);
  const tokenCss = buildTokenCss(tokens);
  const errorTs = buildErrorKeys(errorKeys);
  const avatarOptionsTs = buildAvatarOptions(avatarOptions);
  const avatarEngineTs = buildAvatarEngine(engine);
  const messagesTs = buildMessages(es, en);
  const currenciesTs = buildCurrencies(currencies);

  files.set("frontend-web/app/generated/tokens.generated.css", tokenCss);
  files.set("frontend-web/lib/generated/tokens.ts", tokensTs);
  files.set("frontend-mobile/lib/generated/tokens.ts", tokensTs);
  files.set("frontend-web/lib/generated/error-keys.ts", errorTs);
  files.set("frontend-mobile/lib/generated/error-keys.ts", errorTs);
  files.set("frontend-web/lib/avatar-options.generated.ts", avatarOptionsTs);
  files.set("frontend-mobile/lib/avatar-options.generated.ts", avatarOptionsTs);
  files.set("frontend-web/lib/avatar-engine.generated.ts", avatarEngineTs);
  files.set("frontend-mobile/lib/avatar-engine.generated.ts", avatarEngineTs);
  files.set("frontend-web/lib/i18n/messages.generated.ts", messagesTs);
  files.set("frontend-mobile/lib/i18n/messages.generated.ts", messagesTs);
  files.set("frontend-web/lib/currencies.generated.ts", currenciesTs);
  files.set("frontend-mobile/lib/currencies.generated.ts", currenciesTs);

  return files;
}

export async function writeFiles() {
  const files = await buildFiles();
  for (const [relativePath, content] of files) {
    const absolutePath = path.join(root, relativePath);
    await mkdir(path.dirname(absolutePath), { recursive: true });
    await writeFile(absolutePath, content);
  }
  return [...files.keys()];
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  if (process.argv.includes("--check")) {
    const files = await buildFiles();
    const stale = [];
    for (const [relativePath, expected] of files) {
      let actual = "";
      try {
        actual = await readFile(path.join(root, relativePath), "utf8");
      } catch {
        actual = "";
      }
      if (actual !== expected) stale.push(relativePath);
    }
    if (stale.length) {
      process.stderr.write(`Stale generated files:\n${stale.join("\n")}\n`);
      process.exitCode = 1;
    } else {
      process.stdout.write(`Generated ${files.size} files are up to date\n`);
    }
  } else {
    writeFiles().then((files) => {
      process.stdout.write(`Generated ${files.length} files\n`);
    });
  }
}
